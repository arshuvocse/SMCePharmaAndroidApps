package com.creatrix.salessolution.Model;

public class TadaList {
    public String TadaDate;
    public String EmpName;
    public String TaAmt;
    public String DaAmt;
    public String Market;
    public String ApprovalStatus;


    public String getTadaDate() {
        return TadaDate;
    }

    public void setTadaDate(String tadaDate) {
        TadaDate = tadaDate;
    }

    public String getEmpName() {
        return EmpName;
    }

    public void setEmpName(String empName) {
        EmpName = empName;
    }

    public String getTaAmt() {
        return TaAmt;
    }

    public void setTaAmt(String taAmt) {
        TaAmt = taAmt;
    }

    public String getDaAmt() {
        return DaAmt;
    }

    public void setDaAmt(String daAmt) {
        DaAmt = daAmt;
    }

    public String getMarket() {
        return Market;
    }

    public void setMarket(String market) {
        Market = market;
    }

    public String getApprovalStatus() {
        return ApprovalStatus;
    }

    public void setApprovalStatus(String approvalStatus) {
        ApprovalStatus = approvalStatus;
    }
}
