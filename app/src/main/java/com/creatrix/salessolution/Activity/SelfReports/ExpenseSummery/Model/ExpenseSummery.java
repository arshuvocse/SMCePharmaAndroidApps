package com.creatrix.salessolution.Activity.SelfReports.ExpenseSummery.Model;

public class ExpenseSummery {
    String date;
    String daAmount;
    String mileageAmount;
    String expenseAmount;
    String totalAmount;
    String MarketTourType;

    public String getDate() {
        return date;
    }

    public void setDate(String date) {
        this.date = date;
    }

    public String getDaAmount() {
        return daAmount;
    }

    public void setDaAmount(String daAmount) {
        this.daAmount = daAmount;
    }

    public String getMileageAmount() {
        return mileageAmount;
    }

    public void setMileageAmount(String mileageAmount) {
        this.mileageAmount = mileageAmount;
    }

    public String getExpenseAmount() {
        return expenseAmount;
    }

    public void setExpenseAmount(String expenseAmount) {
        this.expenseAmount = expenseAmount;
    }

    public String getTotalAmount() {
        return totalAmount;
    }

    public void setTotalAmount(String totalAmount) {
        this.totalAmount = totalAmount;
    }

    public String getMarketTourType() {
        return MarketTourType;
    }

    public void setMarketTourType(String marketTourType) {
        MarketTourType = marketTourType;
    }

}
