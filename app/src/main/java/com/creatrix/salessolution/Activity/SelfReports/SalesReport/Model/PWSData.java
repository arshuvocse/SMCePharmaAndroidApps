package com.creatrix.salessolution.Activity.SelfReports.SalesReport.Model;

public class PWSData {
    String product_name;
    String order_times;
    String ordered_qty;
    String ordered_value;
    String SN;

    public String getProduct_name() {
        return product_name;
    }

    public void setProduct_name(String product_name) {
        this.product_name = product_name;
    }

    public String getOrder_times() {
        return order_times;
    }

    public void setOrder_times(String order_times) {
        this.order_times = order_times;
    }

    public String getOrdered_qty() {
        return ordered_qty;
    }

    public void setOrdered_qty(String ordered_qty) {
        this.ordered_qty = ordered_qty;
    }

    public String getOrdered_value() {
        return ordered_value;
    }

    public void setOrdered_value(String ordered_value) {
        this.ordered_value = ordered_value;
    }

    public String getSN() {
        return SN;
    }

    public void setSN(String SN) {
        this.SN = SN;
    }
}
